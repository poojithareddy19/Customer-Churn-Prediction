"""Demonstrate drift monitoring with the population stability index (PSI).

The dataset is a single snapshot with no time dimension, so real drift over time cannot be measured. This
script compares (1) the training split with the test split, which should be stable, (2) existing customers
(tenure of 12 months or more) with new customers (under 12 months), a real population difference inside the data,
and (3) the training split with a SIMULATED shifted sample made only of month-to-month contract customers from
the test split.

Usage: python scripts/drift_check.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.features import load_dataset, split_features_target  # noqa: E402
from src.monitoring import PSI_SIGNIFICANT, PSI_STABLE, psi, psi_status  # noqa: E402
from src.train import load_or_train_bundle, split_data  # noqa: E402

OUTPUT_PATH = ROOT / "reports" / "drift_report.md"
MONITORED_COLUMNS = ["tenure", "MonthlyCharges", "TotalCharges", "predicted_probability"]
NEW_CUSTOMER_MONTHS = 12


def _with_scores(frame: pd.DataFrame, bundle) -> pd.DataFrame:
    scored = frame.copy()
    scored["predicted_probability"] = bundle.model.predict_proba(frame[bundle.feature_columns])[:, 1]
    return scored


def compare(reference: pd.DataFrame, current: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for column in MONITORED_COLUMNS:
        value = psi(reference[column].to_numpy(), current[column].to_numpy())
        rows.append({"column": column, "psi": value, "status": psi_status(value)})
    return pd.DataFrame(rows)


def _table(frame: pd.DataFrame) -> str:
    lines = ["| Column | PSI | Status |", "| --- | --- | --- |"]
    lines += [f"| {row.column} | {row.psi:.4f} | {row.status} |" for row in frame.itertuples()]
    return "\n".join(lines)


def _alert_sentence(shifted_columns: list[str]) -> str:
    if not shifted_columns:
        return "Under the SIMULATED shift, every column stays in the stable range, so no alert would be raised."
    verb = "moves" if len(shifted_columns) == 1 else "move"
    return (
        f"Under the SIMULATED shift, {', '.join(shifted_columns)} {verb} beyond the stable range, so the check would "
        "raise an alert and prompt a review or retrain."
    )


def main() -> None:
    bundle = load_or_train_bundle()
    features, target = split_features_target(load_dataset())
    splits = split_data(features, target, 42)
    train = _with_scores(splits.train_features, bundle)
    test = _with_scores(splits.test_features, bundle)
    shifted = test.loc[test["Contract"] == "Month-to-month"]
    everyone = _with_scores(features, bundle)
    existing = everyone.loc[everyone["tenure"] >= NEW_CUSTOMER_MONTHS]
    new = everyone.loc[everyone["tenure"] < NEW_CUSTOMER_MONTHS]

    train_vs_test = compare(train, test)
    existing_vs_new = compare(existing, new)
    train_vs_shifted = compare(train, shifted)

    lines = [
        "# Drift check",
        "",
        "Generated by `python scripts/drift_check.py`.",
        "",
        "**The dataset has no time dimension, so real drift over time cannot be measured here.** This report "
        "runs the PSI check on real data (train vs test, and new vs existing customers) and on one simulated shift. In production the reference would be the training "
        "data and the current sample would be each new month of scored customers.",
        "",
        f"PSI uses 10 bins at the quantiles of the reference sample. Reading: below {PSI_STABLE} stable, "
        f"{PSI_STABLE} to {PSI_SIGNIFICANT} moderate shift, above {PSI_SIGNIFICANT} significant shift. "
        "Predicted probabilities come from the deployed model, which was fitted on train plus validation, so the "
        "training split scores are in-sample.",
        "",
        f"## 1. Training split ({len(train):,}) vs test split ({len(test):,})",
        "",
        "Both come from the same random stratified split, so they should be stable.",
        "",
        _table(train_vs_test),
        "",
        f"## 2. Existing customers ({len(existing):,}, tenure {NEW_CUSTOMER_MONTHS}+ months) vs new customers "
        f"({len(new):,}, under {NEW_CUSTOMER_MONTHS} months)",
        "",
        "A real split of all 7,043 customers: a new-customer population compared with the existing base, which is "
        "what the model would see if acquisition grew faster than the base. tenure and TotalCharges differ by "
        "construction; the informative rows are MonthlyCharges and the predicted probability. Most of these "
        "customers were in the model's training data, so their scores are in-sample.",
        "",
        _table(existing_vs_new),
        "",
        f"New customers pay less per month on average ({new['MonthlyCharges'].mean():.1f} vs "
        f"{existing['MonthlyCharges'].mean():.1f}) and get much higher scores (mean predicted probability "
        f"{new['predicted_probability'].mean():.2f} vs {existing['predicted_probability'].mean():.2f}), so a rise in "
        "the share of new customers would show up straight away in the score distribution.",
        "",
        f"## 3. SIMULATED shift: training split ({len(train):,}) vs month-to-month customers only ({len(shifted):,})",
        "",
        "SIMULATED: this sample is constructed by keeping only month-to-month contract customers from the test "
        "split, to mimic a customer base that moves toward short contracts. It is not observed drift.",
        "",
        _table(train_vs_shifted),
        "",
        _alert_sentence(list(train_vs_shifted.loc[train_vs_shifted["status"] != "stable", "column"])),
        "",
    ]
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(train_vs_test.to_string(index=False))
    print("Existing vs new customers:")
    print(existing_vs_new.to_string(index=False))
    print("SIMULATED shift:")
    print(train_vs_shifted.to_string(index=False))
    print(f"Wrote {OUTPUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
