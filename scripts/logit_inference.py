"""Logistic regression inference with statsmodels: odds ratios, 95% CIs, p-values and a collinearity check.

This is an explanatory model on all 7,043 customers, separate from the deployed predictive model. Two steps
keep the coefficients interpretable:

1. "No internet service" and "No phone service" are collapsed into "No". Otherwise the six internet add-on
   columns each get a "No internet service" dummy identical to InternetService = No (perfect collinearity).
2. MonthlyCharges and TotalCharges are dropped after a variance inflation factor (VIF) check. MonthlyCharges is
   close to the sum of the add-on prices and TotalCharges is close to tenure times MonthlyCharges, so keeping
   them makes the tenure and service coefficients unstable.

Usage: python scripts/logit_inference.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm
from statsmodels.stats.outliers_influence import variance_inflation_factor

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.features import load_dataset, split_features_target  # noqa: E402

CSV_PATH = ROOT / "reports" / "logit_odds_ratios.csv"
REPORT_PATH = ROOT / "reports" / "logit_inference.md"
SCALED_COLUMNS = ["tenure", "MonthlyCharges", "TotalCharges"]
DROPPED_COLUMNS = ["MonthlyCharges", "TotalCharges"]
VIF_LIMIT = 10.0


def design_matrix(features: pd.DataFrame, drop: list[str] | None = None) -> pd.DataFrame:
    """One-hot design matrix with duplicate "No service" levels merged and numeric columns standardised."""
    frame = features.drop(columns=drop or []).replace({"No internet service": "No", "No phone service": "No"})
    matrix = pd.get_dummies(frame, drop_first=True, dtype=float)
    scaled = [column for column in SCALED_COLUMNS if column in matrix]
    matrix[scaled] = (matrix[scaled] - matrix[scaled].mean()) / matrix[scaled].std()
    return matrix


def vif_table(matrix: pd.DataFrame) -> pd.DataFrame:
    with_constant = sm.add_constant(matrix).to_numpy()
    values = [variance_inflation_factor(with_constant, index + 1) for index in range(matrix.shape[1])]
    return pd.DataFrame({"feature": matrix.columns, "vif": values}).sort_values("vif", ascending=False).reset_index(drop=True)


def odds_ratio_table(target: pd.Series, matrix: pd.DataFrame) -> pd.DataFrame:
    result = sm.Logit(target, sm.add_constant(matrix)).fit(disp=0)
    intervals = np.exp(result.conf_int())
    table = pd.DataFrame(
        {
            "odds_ratio": np.exp(result.params),
            "ci_low": intervals[0],
            "ci_high": intervals[1],
            "p_value": result.pvalues,
        }
    ).drop(index="const")
    table.index.name = "feature"
    return table.sort_values("p_value")


def _markdown(frame: pd.DataFrame, columns: dict[str, str]) -> str:
    lines = ["| " + " | ".join(columns.values()) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    for row in frame.itertuples(index=False):
        lines.append("| " + " | ".join(str(getattr(row, key)) for key in columns) + " |")
    return "\n".join(lines)


def main() -> None:
    features, target = split_features_target(load_dataset())
    full_vif = vif_table(design_matrix(features))
    reduced = design_matrix(features, drop=DROPPED_COLUMNS)
    reduced_vif = vif_table(reduced)
    if reduced_vif["vif"].max() >= VIF_LIMIT:
        raise SystemExit(f"Largest VIF is still {reduced_vif['vif'].max():.1f}; do not interpret the coefficients.")
    table = odds_ratio_table(target, reduced)

    CSV_PATH.parent.mkdir(parents=True, exist_ok=True)
    table.round({"odds_ratio": 3, "ci_low": 3, "ci_high": 3, "p_value": 4}).to_csv(CSV_PATH)

    shown = table.reset_index().head(15)
    shown["odds_ratio"] = shown["odds_ratio"].map("{:.3f}".format)
    shown["ci"] = [f"{low:.3f} to {high:.3f}" for low, high in zip(table["ci_low"].head(15), table["ci_high"].head(15))]
    shown["p_value"] = shown["p_value"].map(lambda value: "<0.0001" if value < 1e-4 else f"{value:.4f}")
    vif_rows = full_vif.loc[(full_vif.index < 5) | full_vif["feature"].isin(SCALED_COLUMNS)]
    vif_rows = vif_rows.assign(vif=lambda frame: frame["vif"].map("{:.1f}".format))
    reduced_rows = reduced_vif.head(5).assign(vif=lambda frame: frame["vif"].map("{:.1f}".format))

    lines = [
        "# Logistic regression inference",
        "",
        "Generated by `python scripts/logit_inference.py`. A statsmodels `Logit` fitted on all "
        f"{len(target):,} customers, for interpretation only; the deployed model is the calibrated XGBoost.",
        "",
        "\"No internet service\" and \"No phone service\" are merged into \"No\", so each add-on has a single "
        "dummy and InternetService = No carries the no-internet effect. tenure is standardised, so its odds "
        "ratio is per one standard deviation.",
        "",
        "## Collinearity check",
        "",
        "Largest variance inflation factors with every column included, plus the three numeric columns:",
        "",
        _markdown(vif_rows, {"feature": "Feature", "vif": "VIF"}),
        "",
        f"MonthlyCharges and TotalCharges are dropped. Largest VIFs after the drop (all below {VIF_LIMIT:.0f}):",
        "",
        _markdown(reduced_rows, {"feature": "Feature", "vif": "VIF"}),
        "",
        "## Odds ratios",
        "",
        f"The 15 most significant terms. Full table: `{CSV_PATH.relative_to(ROOT).as_posix()}`.",
        "",
        _markdown(shown, {"feature": "Feature", "odds_ratio": "Odds ratio", "ci": "95% CI", "p_value": "p-value"}),
        "",
    ]
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(full_vif.head(5).to_string(index=False))
    print(reduced_vif.head(5).to_string(index=False))
    print(table.head(15).round(4).to_string())
    print(f"Wrote {REPORT_PATH.relative_to(ROOT)} and {CSV_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
