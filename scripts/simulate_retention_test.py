"""SIMULATED retention experiment readout.

The dataset has no treatment or control groups, so this script cannot measure a real offer effect. It takes
the customers the deployed model flags on the test split, uses their observed retention rate as the control
baseline, applies an ASSUMED treatment effect and runs the planned analysis on simulated outcomes. The point
is to show the sample size, SRM check and readout format, not to estimate anything.

Usage: python scripts/simulate_retention_test.py [--effect 0.05] [--seed 42]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.experiment import analyze_ab, sample_size_two_proportions, simulate_experiment, srm_check  # noqa: E402
from src.features import load_dataset, split_features_target  # noqa: E402
from src.train import load_or_train_bundle, split_data  # noqa: E402

OUTPUT_PATH = ROOT / "reports" / "SIMULATED_experiment_readout.md"
MDE_GRID = (0.02, 0.03, 0.05, 0.10)


def _pp(value: float) -> str:
    return f"{value * 100:+.1f} pp"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--effect", type=float, default=0.05, help="assumed absolute lift in retention (default 0.05)")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--alpha", type=float, default=0.05)
    parser.add_argument("--power", type=float, default=0.8)
    args = parser.parse_args()

    bundle = load_or_train_bundle()
    features, target = split_features_target(load_dataset())
    splits = split_data(features, target, 42)
    probabilities = bundle.model.predict_proba(splits.test_features[bundle.feature_columns])[:, 1]
    eligible = probabilities >= bundle.threshold
    eligible_n = int(eligible.sum())
    base_retention = float(1 - splits.test_target.to_numpy()[eligible].mean())
    eligible_share = eligible_n / len(probabilities)
    full_base_eligible = round(eligible_share * len(features))

    required_per_arm = sample_size_two_proportions(base_retention, args.effect, args.alpha, args.power)
    mde_rows = [(mde, sample_size_two_proportions(base_retention, mde, args.alpha, args.power)) for mde in MDE_GRID]

    outcome = simulate_experiment(eligible_n, base_retention, args.effect, args.seed)
    srm_p = srm_check(outcome["n_control"], outcome["n_treatment"])
    result = analyze_ab(outcome["retained_control"], outcome["n_control"], outcome["retained_treatment"], outcome["n_treatment"], args.alpha)
    powered = min(outcome["n_control"], outcome["n_treatment"]) >= required_per_arm
    significant = result["p_value"] < args.alpha
    if powered:
        power_note = "The simulated sample is large enough for the assumed effect."
    elif significant:
        power_note = (
            "The simulated sample is underpowered for the assumed effect, and significant estimates from underpowered "
            "tests tend to overstate the true effect."
        )
    else:
        power_note = (
            "Because the simulated sample is underpowered for the assumed effect, a non-significant result does not show "
            "that the offer fails; this many customers cannot reliably detect an effect of this size."
        )

    lines = [
        "SIMULATED DATA: this is not a real experiment result.",
        "",
        "# SIMULATED retention experiment readout",
        "",
        f"Generated by `python scripts/simulate_retention_test.py --effect {args.effect} --seed {args.seed}`. "
        "The dataset contains no treatment or control groups, so every outcome below is drawn from a random "
        "number generator using an assumed effect. See `docs/experiment_plan.md` for the real test design.",
        "",
        "## Inputs",
        "",
        "| Input | Value | Source |",
        "| --- | --- | --- |",
        f"| Eligible customers | {eligible_n:,} | test split customers at or above the deployed threshold {bundle.threshold:.2f} |",
        f"| Eligible share | {eligible_share:.1%} | same, as a share of the {len(probabilities):,} test customers |",
        f"| Control retention rate | {base_retention:.1%} | observed share of eligible test customers with Churn = No |",
        f"| Treatment effect | {_pp(args.effect)} | ASSUMED, not measured |",
        f"| Significance level, power | {args.alpha}, {args.power} | two-sided test, 50/50 split |",
        "",
        "The IBM dataset documentation describes Churn as customers who left within the last month, so it is only a "
        "proxy for the planned 90-day retention metric.",
        "",
        "## Sample size",
        "",
        f"Detecting {_pp(args.effect)} over a {base_retention:.1%} baseline needs **{required_per_arm:,} customers per arm** "
        f"({2 * required_per_arm:,} in total).",
        "",
        "| Minimum detectable effect | Customers per arm | Total |",
        "| --- | --- | --- |",
        *[f"| {_pp(mde)} | {n:,} | {2 * n:,} |" for mde, n in mde_rows],
        "",
        f"The test split has {eligible_n:,} eligible customers, so it is "
        f"{'large enough' if powered else 'too small'} for this effect. Applying the same eligible share to all "
        f"{len(features):,} customers gives about {full_base_eligible:,} eligible customers, which is "
        f"{'enough' if full_base_eligible >= 2 * required_per_arm else 'still not enough'} for a {_pp(args.effect)} MDE.",
        "",
        "## Sample-ratio-mismatch check (SIMULATED)",
        "",
        f"Control {outcome['n_control']:,}, treatment {outcome['n_treatment']:,}, chi-square p-value {srm_p:.3f}. "
        f"{'No mismatch at the 0.001 alarm level.' if srm_p >= 0.001 else 'Mismatch: stop and investigate assignment before reading results.'}",
        "",
        "## Result (SIMULATED)",
        "",
        "| Arm | Customers | Retained | Retention rate |",
        "| --- | --- | --- | --- |",
        f"| Control (no offer) | {outcome['n_control']:,} | {outcome['retained_control']:,} | {result['control_rate']:.1%} |",
        f"| Treatment (offer) | {outcome['n_treatment']:,} | {outcome['retained_treatment']:,} | {result['treatment_rate']:.1%} |",
        "",
        f"Absolute lift {_pp(result['absolute_lift'])}, 95% CI {_pp(result['ci_lower'])} to {_pp(result['ci_upper'])}, "
        f"two-proportion z-test p = {result['p_value']:.3f}.",
        "",
        "## Interpretation (SIMULATED)",
        "",
        f"The simulated lift is {'statistically significant' if significant else 'not statistically significant'} at "
        f"alpha = {args.alpha}. {power_note} A real decision needs the real experiment described in the plan.",
        "",
    ]
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
