"""Run the SQL segment queries, add Wilson intervals and write a markdown summary.

Usage: python scripts/segment_analysis.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.segments import add_wilson_columns, run_sql_file, sql_files  # noqa: E402

OUTPUT_DIR = ROOT / "reports" / "segments"
SUMMARY_PATH = ROOT / "reports" / "segment_analysis.md"
CAVEAT = "This is correlational, not causal."


def _pct(value: float) -> str:
    return f"{value:.1%}"


def _rate_with_ci(row: pd.Series) -> str:
    return f"{_pct(row['churn_rate'])} (95% CI {_pct(row['churn_rate_ci_lower'])} to {_pct(row['churn_rate_ci_upper'])})"


def _format_cell(column: str, value) -> str:
    if isinstance(value, float):
        if "rate" in column or "share" in column:
            return _pct(value)
        return f"{value:,.2f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def markdown_table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(frame.columns) + " |"
    divider = "| " + " | ".join("---" for _ in frame.columns) + " |"
    body = [
        "| " + " | ".join(_format_cell(column, value) for column, value in zip(frame.columns, row)) + " |"
        for row in frame.astype(object).itertuples(index=False)
    ]
    return "\n".join([header, divider, *body])


def build_findings(results: dict[str, pd.DataFrame]) -> list[str]:
    overall = results["01_overall"].iloc[0]
    tenure = results["02_tenure_cohorts"].set_index("tenure_cohort")
    contract_payment = results["03_contract_payment"]
    service = results["04_service_mix"]
    bands = results["05_charge_bands"].set_index("charge_band")
    revenue = results["06_revenue_at_risk"]

    newest, longest = tenure.loc["0-6"], tenure.loc["49+"]
    top_segment = contract_payment.iloc[0]
    worst_service, best_service = service.iloc[0], service.loc[service["internet_service"] != "No"].iloc[-1]
    highest_band = bands["churn_rate"].idxmax()
    top_revenue = revenue.iloc[0]

    return [
        (
            f"Churn is concentrated early in the customer lifetime. Customers in their first 6 months churn at "
            f"{_rate_with_ci(newest)}, against {_rate_with_ci(longest)} for customers past 48 months "
            f"(overall rate {_pct(overall['churn_rate'])}). {CAVEAT}"
        ),
        (
            f"{top_segment['contract']} customers paying by {top_segment['payment_method'].lower()} are the largest "
            f"high-risk segment: {top_segment['customers']:,} customers ({_pct(top_segment['customers'] / overall['customers'])} "
            f"of the base) churn at {_rate_with_ci(top_segment)} and account for "
            f"{_pct(top_segment['share_of_all_churners'])} of all churners. {CAVEAT}"
        ),
        (
            f"{worst_service['internet_service']} customers without online security and without tech support churn at "
            f"{_rate_with_ci(worst_service)}, while {best_service['internet_service']} customers with both churn at "
            f"{_rate_with_ci(best_service)}. Customers who choose add-on services may differ in other ways, so this "
            f"does not show that selling the add-ons would reduce churn. {CAVEAT}"
        ),
        (
            f"Churn rises with monthly charges but is not strictly monotonic. The lowest charge band "
            f"(average {bands.loc[1, 'avg_monthly_charges']:.2f} per month) churns at {_rate_with_ci(bands.loc[1])}, "
            f"band {highest_band} (average {bands.loc[highest_band, 'avg_monthly_charges']:.2f}) is highest at "
            f"{_rate_with_ci(bands.loc[highest_band])}, and the top band (average {bands.loc[5, 'avg_monthly_charges']:.2f}) "
            f"is {_rate_with_ci(bands.loc[5])}. {CAVEAT}"
        ),
        (
            f"{top_revenue['contract']} contracts hold {_pct(top_revenue['share_of_lost_revenue'])} of the monthly revenue "
            f"lost to churn ({top_revenue['churned_monthly_revenue']:,.2f} of "
            f"{revenue['churned_monthly_revenue'].sum():,.2f} per month), so retention spend aimed at this group covers "
            f"most of the revenue at risk. {CAVEAT}"
        ),
    ]


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    results: dict[str, pd.DataFrame] = {}
    for path in sql_files():
        frame = add_wilson_columns(run_sql_file(path))
        results[path.stem] = frame
        frame.to_csv(OUTPUT_DIR / f"{path.stem}.csv", index=False, float_format="%.6f")

    lines = [
        "# Segment and cohort analysis",
        "",
        "Generated by `python scripts/segment_analysis.py` from the queries in `sql/`, run with DuckDB directly on "
        "`WA_Fn-UseC_-Telco-Customer-Churn.csv` (all 7,043 customers, not only the test split). Churn rate intervals "
        "are 95% Wilson score intervals.",
        "",
        "**Every finding below is correlational, not causal.** The dataset is a single observational snapshot with no "
        "intervention, so a segment with high churn shows where to look, not what would change the outcome.",
        "",
        "## Findings",
        "",
        *[f"{index}. {finding}" for index, finding in enumerate(build_findings(results), start=1)],
        "",
        "## Tables",
        "",
    ]
    for name, frame in results.items():
        lines += [f"### {name}", "", f"Source: `sql/{name}.sql`, saved to `reports/segments/{name}.csv`.", "", markdown_table(frame), ""]
    SUMMARY_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(results)} tables to {OUTPUT_DIR.relative_to(ROOT)} and {SUMMARY_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
